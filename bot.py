def handle_update(upd):
    if "message" in upd:
        m = upd["message"]
        chat = m.get("chat") or {}
        chat_id = chat.get("id")
        if chat_id is None:
            return
        name = chat.get("first_name") or chat.get("title") or "there"
        text = m.get("text") or m.get("caption") or ""

        doc = m.get("document")
        if doc and (doc.get("file_size") or 0) < 3 * 1024 * 1024:
            content = get_file_text(doc["file_id"])
            if content and (looks_like_cookies(content) or chat_id in WAITING_COOKIES
                            or to_netscape(content)):
                if handle_cookie_input(chat_id, content):
                    return

        if text.startswith("/start"):
            handle_start(chat_id, name)
            return
        if text.startswith("/help"):
            handle_help(chat_id)
            return
        if text.startswith("/about"):
            handle_about(chat_id)
            return
        if text.startswith("/cookies"):
            handle_cookies_info(chat_id)
            return
        if text.startswith("/status"):
            handle_status(chat_id)
            return

        urls = [u.rstrip(".,);]") for u in URL_RE.findall(text)]
        if urls:
            seen = []
            for u in urls[:5]:
                if u not in seen:
                    seen.append(u)
            for u in seen:
                fetch_and_prompt(chat_id, u)
            return

        if looks_like_cookies(text) or chat_id in WAITING_COOKIES:
            if handle_cookie_input(chat_id, text):
                return
            if chat_id in WAITING_COOKIES:
                send_message(chat_id, "🤔 Hmm, that doesn't look like cookies.\n"
                             "Send a <code>cookies.txt</code>, a JSON export, or a "
                             "<code>name=value; ...</code> string. Or just paste a link 🔗")
                return

        if text:
            send_message(chat_id, "🔗 <b>Send me a video link</b> and I'll download it for you! 🎬",
                         main_menu())
        return

    if "callback_query" in upd:
        cb = upd["callback_query"]
        cb_id = cb.get("id")
        data = cb.get("data") or ""
        msg = cb.get("message") or {}
        chat_id = (msg.get("chat") or {}).get("id")
        mid = msg.get("message_id")
        if data == "help":
            answer_cb(cb_id)
            handle_help(chat_id, mid)
        elif data == "about":
            answer_cb(cb_id)
            handle_about(chat_id, mid)
        elif data == "cookies":
            answer_cb(cb_id)
            handle_cookies_info(chat_id, mid)
        elif data == "status":
            answer_cb(cb_id)
            handle_status(chat_id, mid)
        elif data == "back":
            answer_cb(cb_id)
            edit_message(chat_id, mid, "👋 <b>Send me a link to get started!</b> 🔗", main_menu())
        elif data == "cancel_cookie":
            answer_cb(cb_id, "Okay 👍")
            WAITING_COOKIES.discard(chat_id)
            edit_message(chat_id, mid, "👍 No problem. Send a link anytime!", main_menu())
        elif data.startswith("v:"):
            parts = data.split(":")
            height = int(parts[2]) if len(parts) > 2 and parts[2].isdigit() and int(parts[2]) > 0 else None
            deliver(chat_id, parts[1], "video", height, cb_id)
        elif data.startswith("a:"):
            deliver(chat_id, data.split(":", 1)[1], "audio", None, cb_id)
        elif data.startswith("x:"):
            answer_cb(cb_id, "Cancelled")
            if mid:
                edit_message(chat_id, mid, "❌ <b>Cancelled.</b>", None)
        return



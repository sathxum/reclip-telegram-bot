def animate_fetch(chat_id, mid, stop):
    frames = ["🔍", "🧩", "⚙️", "🧠", "🛰"]
    i = 0
    while not stop.is_set() and time.time() < DEADLINE:
        try:
            edit_message(chat_id, mid, frames[i % len(frames)] + " <b>Fetching video info…</b>")
        except Exception:
            pass
        i += 1
        if stop.wait(1.4):
            break



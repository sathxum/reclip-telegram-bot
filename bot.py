def janitor_loop():
    while time.time() < DEADLINE + 120:
        time.sleep(45)
        now = time.time()
        try:
            if os.path.isfile(COOKIE_FILE) and (now - COOKIE_META["ts"]) > COOKIE_TTL:
                purge_cookies("ttl expired")
            for f in glob.glob(os.path.join(DL, "*")):
                try:
                    if os.path.isfile(f) and (now - os.path.getmtime(f)) > FILE_TTL:
                        os.remove(f)
                except OSError:
                    pass
        except Exception as exc:
            log("janitor exc", exc)



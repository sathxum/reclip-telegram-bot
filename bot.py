def _ns_header():
    return "# Netscape HTTP Cookie File\n# Generated by ReClip (temporary)\n\n"


def to_netscape(text):
    """Convert cookies from almost ANY format to Netscape format.

    Supported: Netscape cookies.txt, JSON exports (Cookie-Editor /
    EditThisCookie / Firefox), raw 'name=value; name2=value2' strings,
    and base64 of any of the above.
    """
    if not text:
        return None
    raw = text.strip()
    try:
        dec = base64.b64decode(raw, validate=True).decode("utf-8", "ignore")
        if dec and ("Netscape" in dec or dec.strip()[:1] in "[{" or "\t" in dec or "=" in dec):
            raw = dec.strip()
    except Exception:
        pass

    low = raw.lower()
    if raw.startswith("#") and "netscape" in low and "\t" in raw:
        return raw if raw.endswith("\n") else raw + "\n"

    if raw[:1] in "[{":
        try:
            data = json.loads(raw)
        except Exception:
            data = None
        if data is not None:
            if isinstance(data, dict):
                data = data.get("cookies") or data.get("Cookies") or [data]
            lines = [_ns_header()]
            n = 0
            for c in data:
                if not isinstance(c, dict):
                    continue
                name = c.get("name")
                value = c.get("value")
                domain = c.get("domain") or c.get("host") or c.get("host_key")
                if not name or value is None or not domain:
                    continue
                path = c.get("path") or "/"
                secure = "TRUE" if (c.get("secure") or c.get("is_secure")) else "FALSE"
                exp = c.get("expirationDate") or c.get("expires") or c.get("expiry")
                try:
                    exp = int(float(exp))
                except Exception:
                    exp = int(time.time() + 86400 * 365)
                dom = str(domain)
                if not dom.startswith("."):
                    dom = "." + dom
                lines.append("\t".join([dom, "TRUE", str(path), secure,
                                        str(exp), str(name), str(value)]))
                n += 1
            if n:
                return "\n".join(lines) + "\n"
        return None

    if "\t" in raw:
        return raw if raw.endswith("\n") else raw + "\n"

    if "=" in raw:
        dom = ".youtube.com"
        for cand in (".instagram.com", ".youtube.com", ".googlevideo.com", ".google.com"):
            if cand in raw:
                dom = cand
                break
        body = raw
        head = raw.split(";")[0]
        if ":" in head and head.split(":")[0].strip().lower() in ("cookie", "cookies"):
            body = raw.split(":", 1)[1]
        pairs = []
        for part in body.split(";"):
            part = part.strip()
            if "=" not in part:
                continue
            k, v = part.split("=", 1)
            k, v = k.strip(), v.strip()
            if k and k.lower() not in ("cookie", "cookies"):
                pairs.append((k, v))
        if pairs:
            lines = [_ns_header()]
            for k, v in pairs:
                lines.append("\t".join([dom, "TRUE", "/", "TRUE",
                                        str(int(time.time() + 86400 * 365)), k, v]))
            return "\n".join(lines) + "\n"
    return None


def looks_like_cookies(text):
    if not text or len(text) < 20:
        return False
    t = text.strip()
    if t.startswith("http://") or t.startswith("https://"):
        return False
    low = t.lower()
    if "netscape" in low and "\t" in t:
        return True
    if t[:1] in "[{" and ("domain" in low or "name" in low or "cookies" in low):
        return True
    if "youtube.com" in low and ("\t" in t or "=" in t):
        return True
    for tok in ("LOGIN_INFO", "SID=", "HSID=", "SSID=", "APISID=", "SAPISID=", "__Secure"):
        if tok in t:
            return True
    if "\n" not in t and t.count("=") >= 3 and ";" in t and not t.startswith("http"):
        return True
    try:
        dec = base64.b64decode(t, validate=True).decode("utf-8", "ignore")
        if dec and ("netscape" in dec.lower() or dec.strip()[:1] in "[{" or "youtube.com" in dec.lower()):
            return True
    except Exception:
        pass
    return False


def cookie_valid():
    return os.path.isfile(COOKIE_FILE) and (time.time() - COOKIE_META["ts"]) < COOKIE_TTL


def save_cookies(text, who):
    ns = to_netscape(text)
    if not ns:
        return 0
    try:
        with open(COOKIE_FILE, "w") as fh:
            fh.write(ns)
    except Exception as exc:
        log("cookie write err", exc)
        return 0
    n = sum(1 for l in ns.splitlines() if l.strip() and not l.startswith("#"))
    COOKIE_META.update({"ts": time.time(), "n": n, "who": str(who)})
    log("cookies saved:", n, "for", who)
    return n


def purge_cookies(why=""):
    try:
        if os.path.isfile(COOKIE_FILE):
            os.remove(COOKIE_FILE)
    except OSError:
        pass
    COOKIE_META.update({"ts": 0.0, "n": 0})
    if why:
        log("cookies purged:", why)


if os.environ.get("YT_COOKIES", "").strip():
    _seeded = save_cookies(os.environ["YT_COOKIES"], "env")
    log("seeded cookies from env:", _seeded)


